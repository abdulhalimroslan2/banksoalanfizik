function exportJsuToCsv() {
  const selTing = document.getElementById("jsu-select-tingkatan");
  const selPep = document.getElementById("jsu-select-peperiksaan");
  const selKer = document.getElementById("jsu-select-kertas");

  const tingVal = selTing ? selTing.value : "all";
  const pepVal = selPep ? selPep.value : "percubaan";
  const kerVal = selKer ? selKer.value : "kertas2";

  const profileKey = getJsuProfileKey(tingVal, pepVal, kerVal);
  const profile = JSU_PROFILES[profileKey] || JSU_PROFILES["spm_percubaan_k2"];
  profile.profileKey = profileKey;
  if (typeof AppState !== "undefined") {
    AppState.activeJsuProfile = profileKey;
  }

  // Muat semula soalan tersuai dari localStorage jika pernah diubah suai
  try {
    const savedCustom = localStorage.getItem("fizik_jsu_custom_q_" + profileKey);
    if (savedCustom) {
      const parsedQ = JSON.parse(savedCustom);
      if (Array.isArray(parsedQ) && parsedQ.length === profile.questions.length) {
        profile.questions = parsedQ;
      }
    }
  } catch(e) {}

  let csvRows = [];
  csvRows.push([`"${profile.title}"`]);
  csvRows.push([`"Mata Pelajaran: ${profile.subject}"`]);
  csvRows.push([`"Format: ${profile.paperName}"`]);
  csvRows.push([]);

  if (profile.kertas === "kertas2") {
    csvRows.push([
      "NO SOALAN", "BAHAGIAN", "BIDANG PEMBELAJARAN (BAB)", "STANDARD KANDUNGAN (SK) / TAJUK",
      "INGAT_R", "INGAT_S", "INGAT_T",
      "FAHAM_R", "FAHAM_S", "FAHAM_T",
      "APLIKASI_R", "APLIKASI_S", "APLIKASI_T",
      "ANALISIS_R", "ANALISIS_S", "ANALISIS_T",
      "NILAI_R", "NILAI_S", "NILAI_T",
      "CIPTA_R", "CIPTA_S", "CIPTA_T",
      "ARAS_R", "ARAS_S", "ARAS_T",
      "SUB_MARKAH"
    ]);

    profile.questions.forEach(q => {
      csvRows.push([
        q.no, q.section, `"${q.bab}"`, `"${q.sk}"`,
        q.ingat[0], q.ingat[1], q.ingat[2],
        q.faham[0], q.faham[1], q.faham[2],
        q.aplikasi[0], q.aplikasi[1], q.aplikasi[2],
        q.analisis[0], q.analisis[1], q.analisis[2],
        q.nilai[0], q.nilai[1], q.nilai[2],
        q.cipta[0], q.cipta[1], q.cipta[2],
        q.jumlahAras[0], q.jumlahAras[1], q.jumlahAras[2],
        q.submarkah
      ]);
    });
  } else {
    csvRows.push(["NO SOALAN", "TINGKATAN", "BAB", "STANDARD KANDUNGAN", "KONSTRUK", "ARAS", "MARKAH"]);
    profile.questions.forEach(q => {
      csvRows.push([q.no, q.ting, `"${q.bab}"`, `"${q.sk}"`, `"${q.konstruk}"`, q.aras, q.markah]);
    });
  }

  const csvContent = "data:text/csv;charset=utf-8,﻿" + csvRows.map(e => e.join(",")).join("\n");
  const encodedUri = encodeURI(csvContent);
  const link = document.createElement("a");
  link.setAttribute("href", encodedUri);
  link.setAttribute("download", `JSU_${profileKey}_${new Date().toISOString().slice(0, 10)}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}

/**
 * Terapkan JSU ke Kertas Peperiksaan (Enjin Pemasangan Kertas)
 * Otomatis beralih ke paparan Hub Pemasangan dengan Full View (soalan lengkap + skema)
 * TUTUP modal JSU jika terbuka
 */
function applyJsuToPaper() {
  const selKer = document.getElementById("jsu-select-kertas");
  const selPep = document.getElementById("jsu-select-peperiksaan");
  const targetMode = selKer && selKer.value === "kertas1" ? "kertas1" : "kertas2";
  const pepVal = selPep ? selPep.value : "percubaan";

  // 1. Jana kertas mengikut JSU
  if (typeof generatePaperByJSU === "function") {
    generatePaperByJSU(targetMode, { ratio: "5:3:2", levelBalance: "50:50" }, true);
  }

  // 2. Tutup modal JSU jika terbuka
  const modalJsu = document.getElementById("modal-jsu-config");
  if (modalJsu) {
    modalJsu.classList.remove("show");
  }

  // Simpan tetapan ke cache memory
  try {
    const settings = JSON.parse(localStorage.getItem("fizik_jsu_settings") || "{}");
    settings.currentPaperMode = targetMode;
    settings.peperiksaan = pepVal;
    localStorage.setItem("fizik_jsu_settings", JSON.stringify(settings));
    localStorage.setItem("fizik_current_paper", targetMode);
  } catch(e) {}

  if (typeof AppState !== "undefined") {
    AppState.currentPaperMode = targetMode;
  }

  // 3. Beralih secara tertib ke Langkah 2: Semakan Senarai Soalan Berdasarkan JSU
  if (typeof switchWorkflowStage === "function") {
    switchWorkflowStage(2);
  }

  if (typeof showJsuNotification === "function") {
    const paperNames = {
      kertas1: "Kertas 1 (Objektif)",
      kertas2: "Kertas 2 (Struktur & Esei)"
    };
    showJsuNotification(`✓ JSU ${paperNames[targetMode] || targetMode} diterapkan — Paparan Soalan Lengkap Aktif`);
  }

  if (window.lucide) lucide.createIcons();
  window.scrollTo({ top: 0, behavior: "smooth" });
}

// Fungsi untuk menandakan stage sebagai selesai
function completeStage(stageNum) {
  if (typeof AppState !== "undefined") {
    if (!AppState.completedStages) AppState.completedStages = [];
    if (!AppState.completedStages.includes(stageNum)) {
      AppState.completedStages.push(stageNum);
    }
    if (typeof updateStepperUI === "function") {
      updateStepperUI(AppState.currentStage || 0);
    }
    // Kembali ke dashboard
    if (typeof switchWorkflowStage === "function") {
      switchWorkflowStage(0);
    }
  }
}
