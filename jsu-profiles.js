/**
 * Padankan Bab daripada String Profil
 */
function findChapterMatch(babStr, chapters) {
  if (!babStr || !chapters || !chapters.length) return chapters ? chapters[0] : null;
  const s = String(babStr).toLowerCase().trim();

  let found = chapters.find(c => c.key.toLowerCase() === s || c.label.toLowerCase() === s);
  if (found) return found;

  const isT4 = s.includes("t4") || s.includes("tingkatan 4");
  const isT5 = s.includes("t5") || s.includes("tingkatan 5");

  const numMatch = s.match(/bab\s*(\d+)/) || s.match(/^(\d+)\./) || s.match(/(\d+)/);
  const num = numMatch ? parseInt(numMatch[1]) : null;

  if (num !== null) {
    if (isT4) found = chapters.find(c => c.tingkatan === 4 && c.babNo === num);
    else if (isT5) found = chapters.find(c => c.tingkatan === 5 && c.babNo === num);
    if (found) return found;
  }

  for (let c of chapters) {
    const nama = c.nama.toLowerCase();
    if (s.includes(nama) || nama.includes(s.replace(/bab\s*\d+/g, "").trim())) {
      return c;
    }
  }

  if (num !== null) {
    found = chapters.find(c => c.babNo === num);
    if (found) return found;
  }

  return chapters[0];
}

/**
 * Escape string untuk HTML attribute
 */
function escapeHtmlAttr(str) {
  if (str === null || str === undefined) return "";
  return String(str).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

